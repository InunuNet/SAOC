// =============================================================
// NOS — e2e/nos-contact.spec.ts
// Mission nos-contact — the National Orchid Show's own /contact page on the NOS host: the header and
// footer Contact links stay on NOS, the SAOC form is reused, and the aside routes to the show pages.
// POST /api/contact sends a real email and writes a real Firestore document, so the request is
// mocked at the browser network boundary (as in contact-form-mocked.spec.ts) and never reaches the
// server.
// =============================================================
import { expect, test } from '@playwright/test';

import { nosBase } from './utils/site-urls';

const ASIDE_ROWS = [
  { label: 'FAQ', href: '/faq' },
  { label: 'Plan your visit', href: '/plan-your-visit' },
  { label: 'What to expect', href: '/what-to-expect' },
];

test.describe('NOS contact page', () => {
  test('/contact is served on the NOS host with the show chrome and Contact links', async ({
    page,
    baseURL,
  }) => {
    await page.setViewportSize({ width: 1440, height: 900 });
    const response = await page.goto(`${nosBase(baseURL!)}/contact`);
    expect(response?.status()).toBe(200);
    expect(new URL(page.url()).pathname).toBe('/contact');

    await expect(page.locator('header#nh')).toHaveCount(1);
    await expect(page.getByRole('heading', { level: 1, name: 'Contact' })).toBeVisible();
    await expect(page.locator('header#nh').getByRole('link', { name: 'Contact', exact: true })).toHaveAttribute(
      'href',
      '/contact',
    );
    await expect(page.locator('footer#nf').getByRole('link', { name: 'Contact', exact: true })).toHaveAttribute(
      'href',
      '/contact',
    );
  });

  test('the aside routes to the show pages', async ({ page, baseURL }) => {
    await page.goto(`${nosBase(baseURL!)}/contact`);

    const aside = page.locator('nav.nos-contact-aside');
    await expect(aside.getByRole('heading', { name: 'Looking for something else' })).toBeVisible();
    for (const { label, href } of ASIDE_ROWS) {
      await expect(aside.getByRole('link', { name: label, exact: true })).toHaveAttribute('href', href);
    }
  });

  test('the form posts to a mocked /api/contact and the success heading takes focus', async ({
    page,
    baseURL,
  }) => {
    let interceptedContactRequest = false;
    let posted: unknown;

    await page.route('**/api/contact', async (route) => {
      interceptedContactRequest = true;
      posted = route.request().postDataJSON();
      await route.fulfill({
        status: 201,
        contentType: 'application/json',
        body: JSON.stringify({ success: true }),
      });
    });

    await page.goto(`${nosBase(baseURL!)}/contact`);
    // The form's submit handler only exists after hydration (see contact-form-mocked.spec.ts).
    await page.waitForLoadState('networkidle');

    await page.locator('#cf-name').fill('Playwright Test');
    await page.locator('#cf-email').fill('playwright-test@example.com');
    await page.locator('#cf-subject').fill('Automated harness check');
    await page
      .locator('#cf-message')
      .fill('This message is generated by the Playwright e2e harness and is mocked.');
    await page.getByRole('button', { name: 'Send message' }).click();

    const heading = page.getByRole('heading', { name: 'Thank you' });
    await expect(heading).toBeVisible();
    await expect(heading).toBeFocused();
    expect(interceptedContactRequest).toBe(true);
    expect(Object.keys(posted as Record<string, unknown>).sort()).toEqual([
      'email',
      'message',
      'name',
      'subject',
    ]);
  });
});
