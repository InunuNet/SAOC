#!/usr/bin/env python3
"""sync_agents_core.py -- render canonical agents (.agent/agents/*.md) into every provider.

Called by execution/sync_agents.sh; paths are relative to the project root (the cwd).

    sync_agents_core.py sync  --targets T --manifests M --toml-dirs D
    sync_agents_core.py check --targets T --skills-dirs S [--manifests M] [--toml-dirs D]

T, M, D, S are "<provider>\\t<path>" lines as enumerated from .agent/providers/*.json.

Skills (canonical `skills: [a, b]` frontmatter line): Claude gets the frontmatter line and
preloads natively; Codex, Grok and Antigravity get each skill body inlined after the role
body between `<!-- athanor-skill:begin NAME -->` / `end` delimiters.

Markdown provider files carry `# athanor-render: body-sha256=<hex>` in their frontmatter.
A file whose body still hashes to that marker (or, unmarked, to a body Athanor once shipped,
see .agent/agents/.shipped-body-hashes.json) is re-rendered after a backup; any other file is
customised: it is kept and the fresh render is written beside it as `<name>.md.athanor-new`.
"""
import argparse
import datetime
import hashlib
import json
import os
import re
import shutil
import sys
from pathlib import Path

try:
    import tomllib
except ImportError:  # Python < 3.11
    tomllib = None

CANONICAL_DIR = Path(".agent/agents")
SKILLS_DIR = Path(".agent/skills")
HASHES_PATH = CANONICAL_DIR / ".shipped-body-hashes.json"
ALLOW_PATH = CANONICAL_DIR / "NO_SKILL_ALLOWLIST.yaml"
BACKUP_ROOT = Path(".agent/memory/scratch/agent-backups")
SKILL_BODY_CAP = 9000
AGENT_SKILL_CAP = 16000
ANTI_SHORT_THRESHOLD = 200
GENERATED = "# Generated by make sync-agents"
NEW_SUFFIX = ".athanor-new"
SIDECAR_SUFFIX = ".athanor-render"
BLOCK_ITEM_RE = re.compile(r"^[ \t]+-[ \t]*([^\s#]+)[ \t]*(?:#.*)?$")
FILE_MARKER_RE = re.compile(r"^#\s*athanor-render:\s*file-sha256=([0-9a-f]{64})\s*$")
SKILL_NAME_RE = re.compile(r"^[a-z0-9-]+$")
MARKER_RE = re.compile(r"^#\s*athanor-render:\s*body-sha256=([0-9a-f]{64})\s*$")
SKILLS_LINE_RE = re.compile(r"^skills:\s*\[(.*)\]\s*$")
BLOCK_RE = re.compile(
    r"<!-- athanor-skill:begin ([a-z0-9-]+) -->\n(.*?)\n<!-- athanor-skill:end \1 -->", re.S)
BLOCK_STRIP_RE = re.compile(
    r"\n*<!-- athanor-skill:begin ([a-z0-9-]+) -->\n.*?\n<!-- athanor-skill:end \1 -->\n?", re.S)
CLAUDE_MODELS = {"apex": "opus", "pro": "opus", "flash": "sonnet", "local": "haiku"}
CLAUDE_TOOLS = {"read": "Read", "write": "Write", "edit": "Edit", "shell": "Bash",
                "grep": "Grep", "search": "WebSearch", "web": "WebFetch"}
GROK_TOOLS = {"read": "read_file", "shell": "run_terminal_command",
              "agent": "spawn_subagent", "task": "spawn_subagent"}


def norm(text):
    return text.replace("\r\n", "\n")


def read_text(path):
    return norm(Path(path).read_text(encoding="utf-8"))


def write_lf(path, text):
    """Atomic LF write: a failed run never leaves a half-written provider file."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".tmp")
    with open(tmp, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    tmp.replace(path)


def text_hash(text):
    return hashlib.sha256(norm(text).rstrip().encode("utf-8")).hexdigest()


def file_hash(text):
    """Hash of a whole rendered file, render-marker lines excluded."""
    kept = [ln for ln in norm(text).split("\n")
            if not (MARKER_RE.match(ln) or FILE_MARKER_RE.match(ln))]
    return text_hash("\n".join(kept))


def body_hash(body):
    return hashlib.sha256(norm(body).rstrip().encode("utf-8")).hexdigest()


def body_hash_variants(body):
    return {body_hash(body), hashlib.sha256(norm(body).strip().encode("utf-8")).hexdigest()}


def split_front(text):
    """(frontmatter lines, body text after the closing --- line)."""
    lines = norm(text).split("\n")
    idx = [i for i, line in enumerate(lines) if line == "---"]
    if len(idx) < 2 or idx[0] != 0:
        return [], norm(text)
    return lines[1:idx[1]], "\n".join(lines[idx[1] + 1:])


def front_value(front, key):
    for line in front:
        if line.startswith(key + ":"):
            return line[len(key) + 1:].strip()
    return None


def parse_list(raw):
    return [item.strip() for item in (raw or "").strip("[]").split(",") if item.strip()]


def parse_pairs(raw):
    return [tuple(line.split("\t", 1)) for line in (raw or "").splitlines() if "\t" in line]


def parse_skills(front):
    """(skills, error) from frontmatter: an inline list or a YAML block list, else an error."""
    idx = [i for i, line in enumerate(front) if line.startswith("skills:")]
    if not idx:
        return [], None
    if len(idx) > 1:
        return [], "duplicate skills: key"
    raw = re.sub(r"\s+#.*$", "", front[idx[0]][len("skills:"):]).strip()
    if raw.startswith("[") and raw.endswith("]"):
        return parse_list(raw), None
    if raw:
        return [], "unsupported skills: line"
    items, pos = [], idx[0] + 1
    while pos < len(front):
        match = BLOCK_ITEM_RE.match(front[pos])
        if not match:
            break
        items.append(match.group(1))
        pos += 1
    if not items or (pos < len(front) and front[pos][:1] in (" ", "\t")):
        return [], "unsupported skills: line"
    return items, None


def load_role(path):
    front, body = split_front(read_text(path))
    description = ""
    for line in front:
        if line.startswith("description:"):
            description = re.sub(r"^description: ?", "", line)
    skills, skills_error = parse_skills(front)
    return {
        "name": Path(path).stem, "tier": (front_value(front, "model_tier") or "").split(" ")[0],
        "description": description, "tools": parse_list(front_value(front, "tools")),
        "denied": parse_list(front_value(front, "tools_denied")), "skills": skills,
        "skills_error": skills_error,
        "body": body, "raw_description": front_value(front, "description") or "",
    }


def load_roles():
    return [load_role(p) for p in sorted(CANONICAL_DIR.glob("*.md"))]


def load_skill_body(name):
    path = SKILLS_DIR / f"{name}.md"
    return split_front(read_text(path))[1].strip() if path.is_file() else None


def validate_skills(roles):
    """Return error lines; load each role's skill bodies into role['skill_bodies']."""
    errors = []
    for role in roles:
        role["skill_bodies"] = []
        total = 0
        if role["skills_error"]:
            errors.append(f"ERROR: .agent/agents/{role['name']}.md has an unsupported `skills:` "
                          f"entry ({role['skills_error']})")
            continue
        for name in role["skills"]:
            if not SKILL_NAME_RE.match(name):
                errors.append(f"ERROR: {role['name']} lists invalid skill name {name!r} "
                              "(allowed: a-z, 0-9, -)")
                continue
            body = load_skill_body(name)
            if body is None:
                errors.append(f"ERROR: {role['name']} lists skill {name} "
                              f"but .agent/skills/{name}.md is missing")
                continue
            size = len(body.encode("utf-8"))
            if not body:
                errors.append(f"ERROR: skill {name} (listed by {role['name']}) has no body")
            elif size > SKILL_BODY_CAP:
                errors.append(f"ERROR: skill {name} body is {size} bytes, over the "
                              f"{SKILL_BODY_CAP}-byte cap")
            total += size
            role["skill_bodies"].append((name, body))
        if total > AGENT_SKILL_CAP:
            errors.append(f"ERROR: {role['name']} inlines {total} bytes of skills, over the "
                          f"{AGENT_SKILL_CAP}-byte cap")
    return list(dict.fromkeys(errors))


def skill_blocks(role):
    return "".join(f"\n\n<!-- athanor-skill:begin {name} -->\n{body}\n"
                   f"<!-- athanor-skill:end {name} -->\n" for name, body in role["skill_bodies"])


def with_inline(body, role):
    return body.rstrip("\n") + skill_blocks(role) if role["skill_bodies"] else body


def dialect_for(provider):
    return {"claude-code": "claude", "grok-cli": "grok"}.get(provider, "default")


def short_name(provider):
    return {"claude-code": "claude", "grok-cli": "grok"}.get(provider, provider)


def map_tools(dialect, tools):
    table = CLAUDE_TOOLS if dialect == "claude" else GROK_TOOLS if dialect == "grok" else {}
    return ", ".join(f'"{table.get(tool, tool)}"' for tool in tools)


def render_md(role, dialect):
    lines = ["---", f"name: {role['name']}"]
    if dialect == "claude":
        lines.append(f"model: {CLAUDE_MODELS.get(role['tier'], 'sonnet')}")
    lines.append(f"description: {role['description']}")
    if dialect == "claude":
        denied = map_tools("claude", role["denied"])
        if denied:
            lines.append(f"disallowedTools: [{denied}]")
        if role["skills"]:
            lines.append(f"skills: [{', '.join(role['skills'])}]")
        body = role["body"].rstrip("\n") + "\n"
    else:
        tools = map_tools(dialect, role["tools"])
        if tools:
            lines.append(f"tools: [{tools}]")
        body = with_inline(role["body"], role).rstrip("\n") + "\n"
    whole = file_hash("\n".join(lines + ["---"]) + "\n" + body)
    lines += [f"# athanor-render: body-sha256={body_hash(body)}",
              f"# athanor-render: file-sha256={whole}", "---"]
    return "\n".join(lines) + "\n" + body


def load_shipped():
    try:
        data = json.loads(HASHES_PATH.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}
    return data if isinstance(data, dict) else {}


def md_managed(current, name, shipped):
    """True when the markdown file is an untouched Athanor render (frontmatter and body)."""
    front, body = split_front(current)
    body_marker = next((m.group(1) for m in map(MARKER_RE.match, front) if m), None)
    file_marker = next((m.group(1) for m in map(FILE_MARKER_RE.match, front) if m), None)
    if body_marker is not None:
        return body_marker == body_hash(body) and file_marker == file_hash(current)
    if file_marker is not None:
        return False
    return bool(body_hash_variants(body) & set(shipped.get(name, [])))


def toml_managed(current, name, shipped):
    lines = norm(current).split("\n")
    marker = next((m.group(1) for m in map(FILE_MARKER_RE.match, lines) if m), None)
    if marker is not None:
        return marker == file_hash(current)
    body = toml_instructions(current)
    if body is None:
        return False
    body = BLOCK_STRIP_RE.sub("", body)
    if body.startswith("## Cross-vendor verdict (Codex)\n\n"):
        body = body.split("\n\n", 2)[-1]
    return bool(body_hash_variants(body) & set(shipped.get(name, [])))


def new_stamp():
    now = datetime.datetime.now(datetime.timezone.utc)
    return f"{now.strftime('%Y%m%dT%H%M%S%f')}Z-{os.getpid()}"


def backup(target, provider, stamp):
    dest = BACKUP_ROOT / stamp / provider / target.name
    suffix = 0
    while dest.exists():
        suffix += 1
        dest = BACKUP_ROOT / stamp / provider / f"{target.name}.{suffix}"
    dest.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(target, dest)


def warn(path, exc, stats):
    print(f"WARN: {path} left untouched ({type(exc).__name__}: {exc})", file=sys.stderr)
    stats["warned"] += 1


def apply_render(target, new, managed, provider, stamp, stats):
    """Create, refresh (after a backup) or keep one provider file; returns the outcome."""
    proposal = target.with_name(target.name + NEW_SUFFIX)
    try:
        if target.is_symlink() and not target.exists():
            raise OSError("dangling symlink")
        if not target.exists():
            write_lf(target, new)
            print(f"create: {target}")
            stats["created"] += 1
            return "created"
        current = target.read_bytes().decode("utf-8", errors="replace")
        if not managed(current):
            print(f"KEPT (customised): {target} (fresh render: {proposal})")
            if not proposal.exists() or proposal.read_bytes() != new.encode("utf-8"):
                write_lf(proposal, new)
            stats["kept"] += 1
            return "kept"
        proposal.unlink(missing_ok=True)
        if norm(current) == new:
            stats["unchanged"] += 1
            return "unchanged"
        backup(target, provider, stamp)
        write_lf(target, new)
        print(f"update: {target}")
        stats["updated"] += 1
        return "updated"
    except OSError as exc:
        warn(target, exc, stats)
        return "warned"


def sync_md(roles, targets, stats, stamp):
    shipped = load_shipped()
    for provider, dest in targets:
        Path(dest).mkdir(parents=True, exist_ok=True)
        for role in roles:
            target = Path(dest) / f"{role['name']}.md"
            apply_render(target, render_md(role, dialect_for(provider)),
                         lambda cur, n=role["name"]: md_managed(cur, n, shipped),
                         short_name(provider), stamp, stats)


def anti_entries(roles):
    result = []
    for role in roles:
        prompt = with_inline(role["body"].lstrip("\n"), role)
        description = role["raw_description"].strip("\"'") or role["name"]
        result.append({"name": role["name"], "description": description, "system_prompt": prompt})
    return result


def anti_managed(current, sidecar, shipped):
    """Marked: whole-file hash equals the sidecar. Unmarked: every prompt is a shipped body."""
    if sidecar.is_file():
        return sidecar.read_text(encoding="utf-8").strip() == file_hash(current)
    try:
        entries = json.loads(current)
        return isinstance(entries, list) and bool(entries) and all(
            isinstance(e, dict) and body_hash_variants(BLOCK_STRIP_RE.sub("", e["system_prompt"]))
            & set(shipped.get(e["name"], [])) for e in entries)
    except (ValueError, KeyError, TypeError):
        return False


def sync_anti(roles, manifests, stats, stamp):
    shipped = load_shipped()
    for provider, manifest in manifests:
        target = Path(manifest)
        result = anti_entries(roles)
        short = [(a["name"], len(a["system_prompt"])) for a in result
                 if len(a["system_prompt"]) < ANTI_SHORT_THRESHOLD]
        if short:
            print(f"ERROR: system_prompt too short (threshold={ANTI_SHORT_THRESHOLD}): {short}",
                  file=sys.stderr)
            return 1
        new = json.dumps(result, indent=2)
        sidecar = target.with_name(target.name + SIDECAR_SUFFIX)
        outcome = apply_render(target, new, lambda cur: anti_managed(cur, sidecar, shipped),
                               short_name(provider), stamp, stats)
        if outcome in ("created", "updated", "unchanged"):
            write_lf(sidecar, file_hash(new) + "\n")
        target.parent.joinpath("register_agents.sh").unlink(missing_ok=True)
        print(f"✅ sync-agents: {target} ({len(result)} agents)")
    return 0


def provider_cfg(provider):
    for path in sorted(Path(".agent/providers").glob("*.json")):
        try:
            cfg = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        if isinstance(cfg, dict) and cfg.get("provider", path.stem) == provider:
            return cfg
    return {}


def toml_str(value):
    """A TOML 1.0 basic string: JSON escaping plus U+007F, which JSON leaves raw."""
    return json.dumps(value, ensure_ascii=False).replace("\x7f", "\\u007f")


def qa_prefix(command):
    return ("## Cross-vendor verdict (Codex)\n\n"
            "You run on an OpenAI model, and so did the code you are reviewing. "
            "Your PASS/FAIL verdict must come from Claude: design the adversarial "
            f'inputs, then run `bash {command} "<review prompt>"` and report its verdict '
            "line verbatim. Never issue a verdict from your own review alone. "
            "If `claude` is not on PATH (the script exits 2), say so in the "
            "verdict and fall back to your own review.\n\n")


def toml_for_role(role, provider, cfg):
    model = (cfg.get("model_map") or {}).get(role["tier"])
    if not model:
        print(f"❌ sync_agents: {role['name']} has model_tier {role['tier']!r} with no "
              f"{provider} model_map entry", file=sys.stderr)
        return None
    reviewer = cfg.get("qa_reviewer") or {}
    qa_flags = {"qa": "", "qa-apex": reviewer.get("apex_flag", "")}
    is_qa = role["name"] in qa_flags and reviewer.get("script")
    body = with_inline(role["body"].lstrip("\n"), role)
    lines = [f"{GENERATED} from .agent/agents/{role['name']}.md. Do not edit.",
             f"name = {toml_str(role['name'])}",
             f"description = {toml_str(role['raw_description'].strip(chr(34) + chr(39)) or role['name'])}",
             f"model = {toml_str(model)}"]
    if is_qa:
        command = " ".join(x for x in (reviewer["script"], qa_flags[role["name"]]) if x)
        body = qa_prefix(command) + body
    lines.append(f"developer_instructions = {toml_str(body)}")
    if is_qa:
        lines += ["", "[sandbox_workspace_write]", "network_access = true"]
    lines.insert(1, f"# athanor-render: file-sha256={file_hash(chr(10).join(lines))}")
    return "\n".join(lines) + "\n"


def sync_toml(roles, toml_dirs, stats, stamp):
    shipped = load_shipped()
    for provider, toml_dir in toml_dirs:
        cfg = provider_cfg(provider)
        supported = (cfg.get("role_capabilities") or {}).get("roles") or {}
        out = Path(toml_dir)
        out.mkdir(parents=True, exist_ok=True)
        written = []
        for role in roles:
            if supported.get(role["name"], {}).get("supported") is False:
                continue
            text = toml_for_role(role, provider, cfg)
            if text is None:
                return 1
            apply_render(out / f"{role['name']}.toml", text,
                         lambda cur, n=role["name"]: toml_managed(cur, n, shipped),
                         short_name(provider), stamp, stats)
            written.append(role["name"])
        for stale in out.glob("*.toml"):
            if stale.stem in written:
                continue
            try:
                if stale.is_symlink() and not stale.exists():
                    raise OSError("dangling symlink")
                current = stale.read_text(encoding="utf-8")
                if not toml_managed(current, stale.stem, shipped):
                    print(f"WARN: customised stale TOML kept: {stale}", file=sys.stderr)
                    continue
                backup(stale, short_name(provider), stamp)
                stale.unlink()
            except (OSError, UnicodeError) as exc:
                warn(stale, exc, stats)
        print(f"✅ sync-agents: {out} ({len(written)} agents)")
    return 0


def run_sync(args):
    roles = load_roles()
    errors = validate_skills(roles)
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    stats = {"created": 0, "updated": 0, "kept": 0, "unchanged": 0, "warned": 0}
    stamp = new_stamp()
    sync_md(roles, parse_pairs(args.targets), stats, stamp)
    print(f"✅ sync_agents: created={stats['created']} updated={stats['updated']} "
          f"kept={stats['kept']} unchanged={stats['unchanged']}")
    rc = sync_anti(roles, parse_pairs(args.manifests), stats, stamp) \
        or sync_toml(roles, parse_pairs(args.toml_dirs), stats, stamp)
    if stats["warned"]:
        print(f"❌ sync_agents: {stats['warned']} file(s) could not be written (see WARN lines)",
              file=sys.stderr)
        return 1
    return rc


def allowed_no_skill():
    if not ALLOW_PATH.is_file():
        return set()
    text = "\n".join(ln for ln in read_text(ALLOW_PATH).split("\n") if not ln.lstrip().startswith("#"))
    match = re.search(r"no_skill_roles:(.*?)(?:\n\S|\Z)", text, re.S)
    return set(re.findall(r"[a-z][a-z0-9-]*", match.group(1))) if match else set()


def check_model_and_skills(role, target, report):
    try:
        front, _ = split_front(read_text(target))
    except (OSError, UnicodeError) as exc:
        report("DRIFT", f"claude {role['name']}: {target} cannot be read ({exc})", True)
        return
    expected = CLAUDE_MODELS.get(role["tier"], "sonnet")
    actual = front_value(front, "model") or ""
    if actual != expected:
        report("DRIFT", f"claude {role['name']}: expected={expected} actual={actual}", True)
    have = set(parse_list(next((m.group(1) for m in map(SKILLS_LINE_RE.match, front) if m), "")))
    if have != set(role["skills"]):
        report("DRIFT", f"skills {role['name']}", True)


def check_skill_files(role, skills_dirs, report):
    for skill in role["skills"]:
        if not (SKILLS_DIR / f"{skill}.md").is_file():
            report("MISSING-SKILL", f"{role['name']}/{skill}", True)
            continue
        for _provider, skills_dir in skills_dirs:
            if not (Path(skills_dir) / skill / "SKILL.md").is_file():
                report("MISSING-SKILL", f"{role['name']}/{skill}", True)
                break


def blocks_match(text, role):
    found = {name: body.strip() for name, body in BLOCK_RE.findall(norm(text))}
    return found == dict(role["skill_bodies"])


def toml_instructions(text):
    """developer_instructions of a Codex TOML, or None when it cannot be parsed."""
    try:
        if tomllib is not None:
            value = tomllib.loads(text).get("developer_instructions")
        else:
            match = re.search(r'^developer_instructions = (".*")$', text, re.M)
            value = json.loads(match.group(1)) if match else None
    except (ValueError, UnicodeError):
        return None
    return value if isinstance(value, str) else None


def check_md(role, targets, report):
    for provider, dest in targets:
        label, target = short_name(provider), Path(dest) / f"{role['name']}.md"
        if not target.is_file():
            report("MISSING", f"{label} {role['name']}: {target} does not exist",
                   bool(role["skills"]))
            continue
        try:
            current = read_text(target)
        except (OSError, UnicodeError) as exc:
            report("DRIFT", f"{label} {role['name']}: {target} cannot be read ({exc})", True)
            continue
        if not md_managed(current, role["name"], load_shipped()):
            report("CUSTOMISED", str(target), False)
        if dialect_for(provider) == "claude":
            check_model_and_skills(role, target, report)
        elif not blocks_match(split_front(current)[1], role):
            report("STALE-INLINE", f"{label} {role['name']}", True)


def check_toml(role, toml_dirs, report):
    for provider, toml_dir in toml_dirs:
        supported = (provider_cfg(provider).get("role_capabilities") or {}).get("roles") or {}
        label, path = short_name(provider), Path(toml_dir) / f"{role['name']}.toml"
        if supported.get(role["name"], {}).get("supported") is False:
            continue
        if not path.is_file():
            report("MISSING", f"{label} {role['name']}: {path} does not exist",
                   bool(role["skills"]))
            continue
        try:
            current = read_text(path)
        except (OSError, UnicodeError) as exc:
            report("DRIFT", f"{label} {role['name']}: {path} cannot be read ({exc})", True)
            continue
        text = toml_instructions(current)
        if text is None:
            report("DRIFT", f"{label} {role['name']}: {path} is not valid TOML", True)
        elif not blocks_match(text, role):
            report("STALE-INLINE", f"{label} {role['name']}", True)


def check_anti(role, manifests, report):
    for provider, manifest in manifests:
        label = short_name(provider)
        try:
            entries = {a["name"]: a["system_prompt"]
                       for a in json.loads(Path(manifest).read_text(encoding="utf-8"))}
        except FileNotFoundError:
            report("MISSING", f"{label} {role['name']}: {manifest} does not exist",
                   bool(role["skills"]))
            continue
        except (OSError, ValueError, KeyError, TypeError):
            report("DRIFT", f"{label} {role['name']}: {manifest} is not a valid manifest", True)
            continue
        if role["name"] not in entries:
            report("MISSING", f"{label} {role['name']}: no entry in {manifest}",
                   bool(role["skills"]))
        elif not blocks_match(entries[role["name"]], role):
            report("STALE-INLINE", f"{label} {role['name']}", True)


def run_check(args):
    roles = load_roles()
    errors = validate_skills(roles)
    targets, skills_dirs = parse_pairs(args.targets), parse_pairs(args.skills_dirs)
    manifests, toml_dirs = parse_pairs(args.manifests), parse_pairs(args.toml_dirs)
    drift = [0]
    seen = set()

    def report(kind, message, counts):
        line = f"{kind} {message}"
        if line not in seen:
            seen.add(line)
            print(line)
            drift[0] += 1 if counts else 0

    for error in errors:
        report("ERROR", error.replace("ERROR: ", ""), True)
    allowed = allowed_no_skill()
    for role in roles:
        if not role["skills"] and role["name"] not in allowed:
            report("NO-SKILL", role["name"], True)
        check_md(role, targets, report)
        check_skill_files(role, skills_dirs, report)
        check_toml(role, toml_dirs, report)
        check_anti(role, manifests, report)
    if drift[0] == 0:
        print(f"✅ sync_agents --check: no drift found ({len(roles)} agents checked)")
        return 0
    print(f"❌ sync_agents --check: {drift[0]} drift(s) found ({len(roles)} agents checked)")
    return 1


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("mode", choices=("sync", "check"))
    parser.add_argument("--targets", default="")
    parser.add_argument("--manifests", default="")
    parser.add_argument("--toml-dirs", default="")
    parser.add_argument("--skills-dirs", default="")
    args = parser.parse_args()
    return run_sync(args) if args.mode == "sync" else run_check(args)


if __name__ == "__main__":
    sys.exit(main())
